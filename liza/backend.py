"""Liza IR -> textual LLVM IR. The host toolchain supplies ABI and linking."""
from .types import INTEGER_TYPES, width, signed, bounds, convert_integer, is_array, is_view, element_type, array_length


def llvm(module):
    class LLVMTypes(dict):
        def __missing__(self, t):
            if is_array(t):
                result = f'[{array_length(t)} x {self[element_type(t)]}]'
            elif is_view(t):
                result = '{ ptr, i32 }'
            else:
                raise KeyError(t)
            self[t] = result
            return result
    types = LLVMTypes({name: f'i{width(name)}' for name in INTEGER_TYPES})
    types['bool'] = 'i1'
    types['File'] = 'i64'  # Private runtime token, never a source-level integer.
    types['Text'] = '{ ptr, i32 }'
    types['integer'] = None  # Only a compile-time conversion literal, never a runtime type.
    structs = getattr(module, 'structs', {})
    types.update({name: f'%struct.{name}' for name in structs})
    variants = getattr(module, 'variants', {})
    types.update({name: f'%variant.{i}' for i,name in enumerate(variants)})
    def large(t):
        # Backend calling convention only; no effect on semantic copyability.
        if is_array(t):
            return array_length(t) > 64 or large(element_type(t))
        if t in structs:
            return any(large(ft) for _, ft in structs[t].fields)
        if t in variants:
            return any(ft is not None and large(ft) for _, ft in variants[t].cases)
        return False
    lines = ['; generated by the experimental Liza compiler', 'declare void @llvm.trap()']
    for name, struct in structs.items():
        members = ', '.join(types[t] for _, t in struct.fields)
        lines.append(f'{types[name]} = type {{ {members} }}')
    for name, variant in variants.items():
        fields = ['i32'] + [types[t] if t is not None else '[0 x i8]' for _,t in variant.cases]
        lines.append(f'{types[name]} = type {{ '+', '.join(fields)+' }')
    for fn in module:
        for block in fn.blocks:
            for op in block.operations:
                if op.op == 'text.literal':
                    data = op.args[0].encode('utf-8')
                    escaped = ''.join('\\%02X' % byte for byte in data)
                    lines.append(f'@text.{fn.name}.{op.result} = private constant [{len(data)} x i8] c"{escaped}"')
    if getattr(module, 'externals', []):
        lines.extend(['declare i64 @liza_rt_write(ptr, i32)',
                      'declare i64 @liza_rt_write_text(ptr, i32)',
                      'declare i64 @liza_rt_print_u64(i64)',
                      'declare i64 @liza_rt_print_i64(i64)'])
        for fn in module.externals:
            t = fn.params[0][1]
            name = fn.name.text
            if name in ('__liza_read_file', '__liza_read_chunk'):
                # Private scalar/pointer ABI only; C never receives an LLVM aggregate.
                chunk = name == '__liza_read_chunk'
                symbol = 'liza_rt_read_chunk' if chunk else 'liza_rt_read_file'
                lines.append(f'declare i64 @{symbol}('+('i64, ptr)' if chunk else 'ptr, i32, ptr)'))
                lines.append(f'define internal void @liza_{name}(ptr sret(%struct.__liza_FileRead) %out, {types[t]} %value) {{')
                if not chunk:
                    lines.extend(['  %path = extractvalue { ptr, i32 } %value, 0',
                                  '  %length = extractvalue { ptr, i32 } %value, 1'])
                lines.append('  %storage = getelementptr %struct.__liza_FileRead, ptr %out, i32 0, i32 0')
                args = 'i64 %value' if chunk else 'ptr %path, i32 %length'
                lines.extend([f'  %status = call i64 @{symbol}({args}, ptr %storage)',
                    '  %status_ptr = getelementptr %struct.__liza_FileRead, ptr %out, i32 0, i32 1',
                    '  store i64 %status, ptr %status_ptr', '  ret void', '}'])
                continue
            if name == '__liza_file_open':
                lines.extend(['declare i32 @liza_rt_file_open(ptr, i32, ptr)',
                    'define internal %struct.__liza_FileOpen @liza___liza_file_open({ ptr, i32 } %value) {',
                    '  %path = extractvalue { ptr, i32 } %value, 0',
                    '  %length = extractvalue { ptr, i32 } %value, 1',
                    '  %slot = alloca i64',
                    '  %error = call i32 @liza_rt_file_open(ptr %path, i32 %length, ptr %slot)',
                    '  %handle = load i64, ptr %slot',
                    '  %base = insertvalue %struct.__liza_FileOpen zeroinitializer, i64 %handle, 0',
                    '  %result = insertvalue %struct.__liza_FileOpen %base, i32 %error, 1',
                    '  ret %struct.__liza_FileOpen %result', '}'])
                continue
            if name == '__liza_file_close':
                lines.extend(['declare i32 @liza_rt_file_close(i64)',
                    'define internal i32 @liza___liza_file_close(i64 %value) {',
                    '  %result = call i32 @liza_rt_file_close(i64 %value)',
                    '  ret i32 %result', '}'])
                continue
            lines.append(f'define i64 @liza_{name}({types[t]} %value) {{')
            if t in ('Text','View<u8>'):
                lines.extend(['  %data = extractvalue { ptr, i32 } %value, 0',
                              '  %length = extractvalue { ptr, i32 } %value, 1',
                              f'  %result = call i64 @liza_rt_write{"_text" if t == "Text" else ""}(ptr %data, i32 %length)'])
            else:
                symbol = 'liza_rt_print_'+t
                lines.append(f'  %result = call i64 @{symbol}(i64 %value)')
            lines.extend(['  ret i64 %result','}'])
    intrinsics = sorted({(op.type, op.op) for fn in module for block in fn.blocks
                         for op in block.operations if op.overflow == 'trap'})
    for type_name, op in intrinsics:
        ty, sign = types[type_name], 's' if signed(type_name) else 'u'
        lines.append(f'declare {{{ty}, i1}} @llvm.{sign}{op}.with.overflow.{ty}({ty}, {ty})')

    def guard(name, condition):
        lines.extend([
            f'  br i1 {condition}, label %{name}_trap, label %{name}_ok',
            f'{name}_trap:', '  call void @llvm.trap()', '  unreachable', f'{name}_ok:',
        ])

    def extend(name, value, source, wide):
        instruction = 'sext' if signed(source) else 'zext'
        lines.append(f'  %{name} = {instruction} {types[source]} {value} to {wide}')
        return f'%{name}'

    def range_checks(name, value, wide, target):
        low, high = bounds(target)
        lines.extend([
            f'  %{name}_below = icmp slt {wide} {value}, {low}',
            f'  %{name}_above = icmp sgt {wide} {value}, {high}',
        ])

    def clamp(name, value, wide, target):
        low, high = bounds(target)
        range_checks(name, value, wide, target)
        lines.extend([
            f'  %{name}_lower = select i1 %{name}_below, {wide} {low}, {wide} {value}',
            f'  %{name}_clamped = select i1 %{name}_above, {wide} {high}, {wide} %{name}_lower',
        ])
        return f'%{name}_clamped'

    for fn in module:
        params = ', '.join((f'ptr byval({types[p["type"]]}) %{p["name"]}_arg'
                            if large(p["type"]) else f'{types[p["type"]]} %{p["name"]}') for p in fn.params)
        indirect_result = large(fn.result_type)
        if indirect_result:
            params = f'ptr sret({types[fn.result_type]}) %return_storage' + (', '+params if params else '')
        result_type = 'void' if indirect_result else types[fn.result_type]
        linkage = 'internal ' if fn.name.startswith('file.') else ''
        lines.append(f'define {linkage}{result_type} @liza_{fn.name}({params}) {{')
        refs = {p['name']: f'%{p["name"]}' for p in fn.params}
        value_types = {p['name']: types[p['type']] for p in fn.params}
        # LLVM guards split semantic blocks. Phi edges reference their final labels.
        exits, aliases = {}, {}
        for block in fn.blocks:
            exits[block.name] = block.name
            for op in block.operations:
                refs[op.result] = str(int(op.args[0])) if op.op == 'constant' else f'%{op.result}'
                if op.op == 'text.literal':
                    size = len(op.args[0].encode('utf-8'))
                    refs[op.result] = f'{{ ptr @text.{fn.name}.{op.result}, i32 {size} }}'
                value_types[op.result] = types[op.type]
                if op.op in ('copy', 'move'):
                    aliases[op.result] = op.args[0]
                if op.op in ('struct.construct', 'array.construct') and not op.args:
                    refs[op.result] = 'zeroinitializer'
                if op.op.startswith('convert.') and op.source_type == 'integer':
                    refs[op.result] = str(convert_integer(int(refs[op.args[0]]), op.type, op.op.split('.')[1]))
                if (op.op == 'convert.checked' and op.source_type != 'integer') or op.overflow == 'trap' or op.shift_policy == 'trap' or op.division_policy == 'trap' or op.bounds_policy == 'trap':
                    exits[block.name] = f'{op.result}_ok'
        # Resolve identities after every SSA reference is known, including
        # forward references across loop backedges and block ordering.
        for name in aliases:
            value = aliases[name]
            while value in aliases:
                value = aliases[value]
            refs[name] = refs[value]
        def canonical(value):
            while value in aliases:
                value = aliases[value]
            return value
        slots = {canonical(op.args[0]) for b in fn.blocks for op in b.operations
                 if op.op in ('array.read', 'view.create')}
        calls = [op for b in fn.blocks for op in b.operations if op.op == 'call']
        signatures = {f.name: [p['type'] for p in f.params] for f in module}
        signatures.update({f.name.text: [t for _,t in f.params] for f in getattr(module,'externals',[])})
        # Acyclic functions execute each return slot at most once. Immutable
        # field projections can borrow that storage directly instead of
        # materializing another complete array. Loops retain the general path.
        def successors(block):
            term = block.terminator
            if term.op in ('return', 'unreachable'): return []
            if term.op == 'branch': return term.args[1:]
            if term.op == 'switch': return [term.args[1]]+[target for _,target in term.args[2:]]
            return [term.args[0]]
        visiting, visited = set(), set()
        blocks_by_name = {b.name:b for b in fn.blocks}
        def cyclic(name):
            if name in visiting: return True
            if name in visited: return False
            visiting.add(name)
            if any(cyclic(n) for n in successors(blocks_by_name[name])): return True
            visiting.remove(name); visited.add(name)
            return False
        has_cycle = cyclic(fn.blocks[0].name)
        operations = {op.result:op for b in fn.blocks for op in b.operations}
        def storage_path(value):
            op = operations.get(canonical(value))
            if op is None: return None
            if op.op == 'call' and large(op.type):
                return op.result, op.type, []
            if op.op not in ('struct.field', 'variant.payload'): return None
            path = storage_path(op.args[0])
            if path is None: return None
            if op.op == 'struct.field':
                index = [f for f,_ in structs[op.source_type].fields].index(op.field_name)
            else:
                index = 1+[c for c,_ in variants[op.source_type].cases].index(op.field_name)
            return path[0], path[1], path[2]+[index]
        shared_slots = {value:storage_path(value) for value in slots} if not has_cycle else {}
        shared_slots = {value:path for value,path in shared_slots.items() if path is not None}
        pending = []

        def flush():
            for value in pending:
                if value in shared_slots: continue
                lines.append(f'  store {value_types[value]} {refs[value]}, ptr %{value}_storage')
            pending.clear()

        for block in fn.blocks:
            lines.append(f'{block.name}:')
            if block is fn.blocks[0]:
                for p in fn.params:
                    if large(p['type']):
                        lines.append(f'  %{p["name"]} = load {types[p["type"]]}, ptr %{p["name"]}_arg')
                for call in calls:
                    if large(call.type):
                        lines.append(f'  %{call.result}_return = alloca {types[call.type]}')
                    for i,t in enumerate(signatures[call.callee]):
                        if large(t):
                            lines.append(f'  %{call.result}_arg{i} = alloca {types[t]}')
                for value in sorted(slots):
                    if value in shared_slots:
                        root,t,path = shared_slots[value]
                        indices = ', '.join('i32 '+str(i) for i in [0]+path)
                        lines.append(f'  %{value}_storage = getelementptr {types[t]}, ptr %{root}_return, {indices}')
                    else:
                        lines.append(f'  %{value}_storage = alloca {value_types[value]}')
                pending.extend(p['name'] for p in fn.params if p['name'] in slots)

            for op in block.operations:
                if op.op != 'phi':
                    flush()
                name, ty = op.result, types[op.type]
                if op.op in ('constant', 'text.literal', 'copy', 'move') or (op.op.startswith('convert.') and op.source_type == 'integer'):
                    continue
                args = [refs[a] for a in op.args]
                if op.op == 'sequence.length':
                    if is_array(op.source_type):
                        lines.append(f'  %{name} = add i32 0, {array_length(op.source_type)}')
                    else:
                        lines.append(f'  %{name} = extractvalue {types[op.source_type]} {args[0]}, 1')
                elif op.op == 'variant.construct':
                    cases = variants[op.type].cases
                    index = next(i for i,(case,_) in enumerate(cases) if case==op.field_name)
                    target = name+'_tag' if args else name
                    lines.append(f'  %{target} = insertvalue {ty} zeroinitializer, i32 {index}, 0')
                    if args:
                        lines.append(f'  %{name} = insertvalue {ty} %{target}, {types[cases[index][1]]} {args[0]}, {index+1}')
                elif op.op in ('variant.tag', 'variant.payload'):
                    index = 0 if op.op == 'variant.tag' else 1+next(i for i,(case,_) in enumerate(variants[op.source_type].cases) if case==op.field_name)
                    lines.append(f'  %{name} = extractvalue {types[op.source_type]} {args[0]}, {index}')
                elif op.op in ('array.read', 'view.create', 'view.read'):
                    if op.op == 'view.create':
                        length = array_length(op.source_type)
                        lines.extend([
                            f'  %{name}_order = icmp ugt i32 {args[1]}, {args[2]}',
                            f'  %{name}_end = icmp ugt i32 {args[2]}, {length}',
                            f'  %{name}_invalid = or i1 %{name}_order, %{name}_end',
                        ])
                        guard(name, f'%{name}_invalid')
                        lines.append(f'  %{name}_length = sub i32 {args[2]}, {args[1]}')
                        lines.append(f'  %{name}_offset = zext i32 {args[1]} to i64')
                        storage = canonical(op.args[0])
                        lines.append(f'  %{name}_ptr = getelementptr {types[op.source_type]}, ptr %{storage}_storage, i64 0, i64 %{name}_offset')
                        lines.append(f'  %{name}_base = insertvalue {ty} zeroinitializer, ptr %{name}_ptr, 0')
                        lines.append(f'  %{name} = insertvalue {ty} %{name}_base, i32 %{name}_length, 1')
                    else:
                        if op.op == 'array.read':
                            length = str(array_length(op.source_type))
                        else:
                            lines.append(f'  %{name}_base = extractvalue {types[op.source_type]} {args[0]}, 0')
                            lines.append(f'  %{name}_length = extractvalue {types[op.source_type]} {args[0]}, 1')
                            length = f'%{name}_length'
                        lines.append(f'  %{name}_invalid = icmp uge i32 {args[1]}, {length}')
                        guard(name, f'%{name}_invalid')
                        lines.append(f'  %{name}_offset = zext i32 {args[1]} to i64')
                        if op.op == 'array.read':
                            storage = canonical(op.args[0])
                            lines.append(f'  %{name}_ptr = getelementptr {types[op.source_type]}, ptr %{storage}_storage, i64 0, i64 %{name}_offset')
                        else:
                            lines.append(f'  %{name}_ptr = getelementptr {ty}, ptr %{name}_base, i64 %{name}_offset')
                        lines.append(f'  %{name} = load {ty}, ptr %{name}_ptr')
                elif op.op == 'array.construct':
                    aggregate = 'zeroinitializer'
                    for index, value in enumerate(args):
                        result = name if index == len(args)-1 else f'{name}_element{index}'
                        lines.append(f'  %{result} = insertvalue {ty} {aggregate}, {types[element_type(op.type)]} {value}, {index}')
                        aggregate = f'%{result}'
                elif op.op == 'struct.construct':
                    aggregate = 'zeroinitializer'
                    for index, (value, (_, field_type)) in enumerate(zip(args, structs[op.type].fields)):
                        result = name if index == len(args) - 1 else f'{name}_field{index}'
                        lines.append(f'  %{result} = insertvalue {ty} {aggregate}, {types[field_type]} {value}, {index}')
                        aggregate = f'%{result}'
                elif op.op == 'struct.field':
                    names = [field for field, _ in structs[op.source_type].fields]
                    index = names.index(op.field_name)
                    lines.append(f'  %{name} = extractvalue {types[op.source_type]} {args[0]}, {index}')
                elif op.op.startswith('convert.'):
                    # i128 holds every supported source value and target bound.
                    # Extend by source signedness, then check/clamp mathematically.
                    value = extend(name + '_wide', args[0], op.source_type, 'i128')
                    if op.op == 'convert.checked':
                        range_checks(name, value, 'i128', op.type)
                        lines.append(f'  %{name}_invalid = or i1 %{name}_below, %{name}_above')
                        guard(name, f'%{name}_invalid')
                    elif op.op == 'convert.saturate':
                        value = clamp(name, value, 'i128', op.type)
                    lines.append(f'  %{name} = trunc i128 {value} to {ty}')
                elif op.overflow == 'saturate':
                    # 2N+1 signed bits hold even the product of two unsigned MAXs.
                    wide = f'i{2 * width(op.type) + 1}'
                    left = extend(name + '_left', args[0], op.type, wide)
                    right = extend(name + '_right', args[1], op.type, wide)
                    lines.append(f'  %{name}_wide = {op.op} {wide} {left}, {right}')
                    value = clamp(name, f'%{name}_wide', wide, op.type)
                    lines.append(f'  %{name} = trunc {wide} {value} to {ty}')
                elif op.op == 'call':
                    actuals = []
                    for i,(a,t) in enumerate(zip(op.args,signatures[op.callee])):
                        if large(t):
                            lines.append(f'  store {types[t]} {refs[a]}, ptr %{name}_arg{i}')
                            actuals.append(f'ptr byval({types[t]}) %{name}_arg{i}')
                        else:
                            actuals.append(f'{value_types[a]} {refs[a]}')
                    if large(op.type):
                        typed = ', '.join([f'ptr sret({ty}) %{name}_return'] + actuals)
                        lines.append(f'  call void @liza_{op.callee}({typed})')
                        lines.append(f'  %{name} = load {ty}, ptr %{name}_return')
                    else:
                        typed = ', '.join(actuals)
                        lines.append(f'  %{name} = call {ty} @liza_{op.callee}({typed})')
                elif op.op == 'phi':
                    incoming = ', '.join(f'[ {value}, %{exits[block_name]} ]'
                                         for value, block_name in zip(args, op.incoming_blocks))
                    lines.append(f'  %{name} = phi {ty} {incoming}')
                elif op.op in ('not', 'bit_not'):
                    mask = 'true' if op.op == 'not' else '-1'
                    lines.append(f'  %{name} = xor {ty} {args[0]}, {mask}')
                elif op.op in ('eq', 'ne', 'ult', 'ule', 'ugt', 'uge', 'slt', 'sle', 'sgt', 'sge'):
                    lines.append(f'  %{name} = icmp {op.op} {value_types[op.args[0]]} {args[0]}, {args[1]}')
                elif op.op in ('shl', 'shr'):
                    bits = width(op.type)
                    lines.append(f'  %{name}_invalid = icmp uge i32 {args[1]}, {bits}')
                    guard(name, f'%{name}_invalid')
                    count = args[1]
                    if bits != 32:
                        cast = 'trunc' if bits < 32 else 'zext'
                        lines.append(f'  %{name}_count = {cast} i32 {count} to {ty}')
                        count = f'%{name}_count'
                    instruction = 'shl' if op.op == 'shl' else ('ashr' if signed(op.type) else 'lshr')
                    lines.append(f'  %{name} = {instruction} {ty} {args[0]}, {count}')
                elif op.op in ('div', 'rem'):
                    lines.append(f'  %{name}_zero = icmp eq {ty} {args[1]}, 0')
                    invalid = f'%{name}_zero'
                    if signed(op.type) and op.op == 'div':
                        lines.extend([
                            f'  %{name}_min = icmp eq {ty} {args[0]}, {bounds(op.type)[0]}',
                            f'  %{name}_minus_one = icmp eq {ty} {args[1]}, -1',
                            f'  %{name}_overflow = and i1 %{name}_min, %{name}_minus_one',
                            f'  %{name}_invalid = or i1 %{name}_zero, %{name}_overflow',
                        ])
                        invalid = f'%{name}_invalid'
                    guard(name, invalid)
                    divisor = args[1]
                    if signed(op.type) and op.op == 'rem':
                        # x % -1 is always zero. Substitute +1 before srem so
                        # MIN % -1 never executes LLVM's undefined operation.
                        lines.extend([
                            f'  %{name}_minus_one = icmp eq {ty} {divisor}, -1',
                            f'  %{name}_divisor = select i1 %{name}_minus_one, {ty} 1, {ty} {divisor}',
                        ])
                        divisor = f'%{name}_divisor'
                    instruction = ('s' if signed(op.type) else 'u') + op.op
                    lines.append(f'  %{name} = {instruction} {ty} {args[0]}, {divisor}')
                elif op.op in ('and', 'or', 'xor') or op.overflow == 'wrap':
                    lines.append(f'  %{name} = {op.op} {ty} {args[0]}, {args[1]}')
                elif op.overflow == 'trap':
                    sign = 's' if signed(op.type) else 'u'
                    lines.extend([
                        f'  %{name}_pair = call {{{ty}, i1}} @llvm.{sign}{op.op}.with.overflow.{ty}({ty} {args[0]}, {ty} {args[1]})',
                        f'  %{name} = extractvalue {{{ty}, i1}} %{name}_pair, 0',
                        f'  %{name}_overflow = extractvalue {{{ty}, i1}} %{name}_pair, 1',
                    ])
                    guard(name, f'%{name}_overflow')
                else:
                    raise ValueError(f'unsupported IR operation: {op.op}')
                if name in slots:
                    pending.append(name)
            flush()
            term = block.terminator
            if term.op == 'return':
                if indirect_result:
                    lines.append(f'  store {types[fn.result_type]} {refs[term.args[0]]}, ptr %return_storage')
                    lines.append('  ret void')
                else:
                    lines.append(f'  ret {types[fn.result_type]} {refs[term.args[0]]}')
            elif term.op == 'unreachable':
                lines.append('  unreachable')
            elif term.op == 'switch':
                cases = ' '.join(f'i32 {index}, label %{target}' for index,target in term.args[2:])
                lines.append(f'  switch i32 {refs[term.args[0]]}, label %{term.args[1]} [ {cases} ]')
            elif term.op == 'branch':
                condition, then, otherwise = term.args
                lines.append(f'  br i1 {refs[condition]}, label %{then}, label %{otherwise}')
            else:
                lines.append(f'  br label %{term.args[0]}')
        lines.append('}')
    lines.extend(['define i32 @main() {', 'entry:', '  %result = call i32 @liza_main()',
                  '  ret i32 %result', '}'])
    return '\n'.join(lines) + '\n'
