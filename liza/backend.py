"""Liza IR -> textual LLVM IR. The host toolchain supplies ABI and linking."""
from .types import is_vec, is_product, product_args
from dataclasses import replace
from .storage import owned_variant, caller_plan
from .types import INTEGER_TYPES, width, signed, bounds, convert_integer, is_array, is_view, element_type, array_length, is_buffer


def llvm(module, target=None):
    class LLVMTypes(dict):
        def __missing__(self, t):
            if is_product(t):
                result = '{ '+', '.join(self[c] for c in product_args(t))+' }'
            elif is_vec(t):
                result = '{ ptr, i32, i32 }'
            elif is_array(t):
                result = f'[{array_length(t)} x {self[element_type(t)]}]'
            elif is_view(t) or is_buffer(t):
                result = '{ ptr, i32 }'
            else:
                raise KeyError(t)
            self[t] = result
            return result
    types = LLVMTypes({name: f'i{width(name)}' for name in INTEGER_TYPES})
    types['bool'] = 'i1'
    types['memory.Region'] = 'ptr'
    types['Arg'] = types['Path'] = 'i32'  # Opaque indices into immutable process arguments.
    types['net.Listener'] = types['net.Stream'] = 'i64'
    types['net.Reactor'] = 'ptr'
    types['net.Connection'] = '[3 x i64]'
    types['File'] = 'i64'  # Private runtime token, never a source-level integer.
    types['Text'] = '{ ptr, i32 }'
    types['integer'] = None  # Only a compile-time conversion literal, never a runtime type.
    structs = getattr(module, 'structs', {})
    types.update({name: f'%struct.{name}' for name in structs})
    variants = getattr(module, 'variants', {})
    types.update({name: f'%variant.{i}' for i,name in enumerate(variants)})
    def weight(t):
        # A layout-independent ABI heuristic: count scalar leaves, not array length.
        if is_product(t): return sum(weight(c) for c in product_args(t))
        if is_array(t): return array_length(t) * weight(element_type(t))
        if t in structs: return sum(weight(ft) for _, ft in structs[t].fields)
        if t in variants: return 1 + sum(weight(ft) for _, ft in variants[t].cases if ft)
        return 1
    def large(t):
        return weight(t) > 64
    lines = ['; generated by the experimental Liza compiler']
    if target is not None:
        lines.extend([f'target datalayout = "{target.data_layout}"',
                      f'target triple = "{target.triple}"'])
    lines.extend(['declare void @llvm.trap()',
             'declare void @llvm.memmove.p0.p0.i64(ptr, ptr, i64, i1)',
             'declare void @llvm.memset.p0.i64(ptr, i8, i64, i1)'])
    memory_used = any(op.op.startswith(('region.', 'buffer.', 'vec.')) for fn in module for block in fn.blocks for op in block.operations)
    if memory_used:
        lines.extend(['declare ptr @liza_rt_region_create(i64, ptr)',
                      'declare ptr @liza_rt_region_alloc(ptr, i64, i64, i32, ptr)',
                      'declare void @liza_rt_region_close(ptr)',
                      'declare ptr @liza_rt_vec_reserve(ptr, ptr, i64, i64, i32, i32, i32, ptr)'])
    def size(t):
        return f'ptrtoint (ptr getelementptr ({types[t]}, ptr null, i32 1) to i64)'
    def transfer(t, source, dest):
        if source != dest:
            lines.append(f'  call void @llvm.memmove.p0.p0.i64(ptr {dest}, ptr {source}, i64 {size(t)}, i1 false)')
    def write(t, value, dest):
        if large(t): transfer(t, value, dest)
        else: lines.append(f'  store {types[t]} {value}, ptr {dest}')
    for name, struct in structs.items():
        members = ', '.join(types[t] for _, t in struct.fields)
        lines.append(f'{types[name]} = type {{ {members} }}')
    for name, variant in variants.items():
        fields = ['i32'] + [types[t] if t is not None else '[0 x i8]' for _,t in variant.cases]
        lines.append(f'{types[name]} = type {{ '+', '.join(fields)+' }')
    for fn in module:
        for block in fn.blocks:
            for op in block.operations:
                if op.op == 'text.literal':
                    data = op.args[0].encode('utf-8')
                    escaped = ''.join('\\%02X' % byte for byte in data)
                    lines.append(f'@text.{fn.name}.{op.result} = private constant [{len(data)} x i8] c"{escaped}"')
    if getattr(module, 'externals', []):
        lines.extend(['declare i64 @liza_rt_write(ptr, i32)',
                      'declare i64 @liza_rt_write_text(ptr, i32)',
                      'declare i64 @liza_rt_print_u64(i64)',
                      'declare i64 @liza_rt_print_i64(i64)',
                      'declare i64 @liza_rt_err_text(ptr, i32)',
                      'declare i64 @liza_rt_err(ptr, i32)',
                      'declare i64 @liza_rt_err_print_u64(i64)',
                      'declare i64 @liza_rt_err_print_i64(i64)'])
        for fn in module.externals:
            from .net_backend import external as net_external
            from .reactor_backend import external as reactor_external
            if reactor_external(fn, lines, types): continue
            if net_external(fn, lines, types):
                continue
            from .cli_backend import external
            if external(fn, lines):
                continue
            t = fn.params[0][1]
            name = fn.name.text
            if name in ('__liza_read_file', '__liza_read_chunk'):
                # Private scalar/pointer ABI only; C never receives an LLVM aggregate.
                chunk = name == '__liza_read_chunk'
                symbol = 'liza_rt_read_chunk' if chunk else 'liza_rt_read_file'
                lines.append(f'declare i64 @{symbol}('+('i64, ptr)' if chunk else 'ptr, i32, ptr)'))
                lines.append(f'define internal void @liza_{name}(ptr sret(%struct.__liza_FileRead) %out, {types[t]} %value) {{')
                if not chunk:
                    lines.extend(['  %path = extractvalue { ptr, i32 } %value, 0',
                                  '  %length = extractvalue { ptr, i32 } %value, 1'])
                lines.append('  %storage = getelementptr %struct.__liza_FileRead, ptr %out, i32 0, i32 0')
                args = 'i64 %value' if chunk else 'ptr %path, i32 %length'
                lines.extend([f'  %status = call i64 @{symbol}({args}, ptr %storage)',
                    '  %status_ptr = getelementptr %struct.__liza_FileRead, ptr %out, i32 0, i32 1',
                    '  store i64 %status, ptr %status_ptr', '  ret void', '}'])
                continue
            if name == '__liza_file_open':
                lines.extend(['declare i32 @liza_rt_file_open(ptr, i32, ptr)',
                    'define internal %struct.__liza_FileOpen @liza___liza_file_open({ ptr, i32 } %value) {',
                    '  %path = extractvalue { ptr, i32 } %value, 0',
                    '  %length = extractvalue { ptr, i32 } %value, 1',
                    '  %slot = alloca i64',
                    '  %error = call i32 @liza_rt_file_open(ptr %path, i32 %length, ptr %slot)',
                    '  %handle = load i64, ptr %slot',
                    '  %base = insertvalue %struct.__liza_FileOpen zeroinitializer, i64 %handle, 0',
                    '  %result = insertvalue %struct.__liza_FileOpen %base, i32 %error, 1',
                    '  ret %struct.__liza_FileOpen %result', '}'])
                continue
            if name == '__liza_file_close':
                lines.extend(['declare i32 @liza_rt_file_close(i64)',
                    'define internal i32 @liza___liza_file_close(i64 %value) {',
                    '  %result = call i32 @liza_rt_file_close(i64 %value)',
                    '  ret i32 %result', '}'])
                continue
            lines.append(f'define i64 @liza_{name}({types[t]} %value) {{')
            if t in ('Text','View<u8>'):
                lines.extend(['  %data = extractvalue { ptr, i32 } %value, 0',
                              '  %length = extractvalue { ptr, i32 } %value, 1',
                              f'  %result = call i64 @liza_rt_{"err" if name.startswith("__liza_err") else "write"}{"_text" if t == "Text" else ""}(ptr %data, i32 %length)'])
            else:
                symbol = 'liza_rt_'+('err_' if name.startswith('__liza_err') else '')+'print_'+t
                lines.append(f'  %result = call i64 @{symbol}(i64 %value)')
            lines.extend(['  ret i64 %result','}'])
    intrinsics = sorted({(op.type, op.op) for fn in module for block in fn.blocks
                         for op in block.operations if op.overflow == 'trap'})
    for type_name, op in intrinsics:
        ty, sign = types[type_name], 's' if signed(type_name) else 'u'
        lines.append(f'declare {{{ty}, i1}} @llvm.{sign}{op}.with.overflow.{ty}({ty}, {ty})')

    def guard(name, condition):
        lines.extend([
            f'  br i1 {condition}, label %{name}_trap, label %{name}_ok',
            f'{name}_trap:', '  call void @llvm.trap()', '  unreachable', f'{name}_ok:',
        ])

    def extend(name, value, source, wide):
        instruction = 'sext' if signed(source) else 'zext'
        lines.append(f'  %{name} = {instruction} {types[source]} {value} to {wide}')
        return f'%{name}'

    def range_checks(name, value, wide, target):
        low, high = bounds(target)
        lines.extend([
            f'  %{name}_below = icmp slt {wide} {value}, {low}',
            f'  %{name}_above = icmp sgt {wide} {value}, {high}',
        ])

    def clamp(name, value, wide, target):
        low, high = bounds(target)
        range_checks(name, value, wide, target)
        lines.extend([
            f'  %{name}_lower = select i1 %{name}_below, {wide} {low}, {wide} {value}',
            f'  %{name}_clamped = select i1 %{name}_above, {wide} {high}, {wide} %{name}_lower',
        ])
        return f'%{name}_clamped'

    owned = {}
    owned_plans = {}
    for function in module:
        plan = owned_variant(function, structs, large)
        if plan is not None:
            index = next(i for i,p in enumerate(function.params) if p['name']==plan.owned_parameter)
            owned[function.name] = (index, plan)
            owned_plans['__liza_owned_'+function.name] = plan
    functions = list(module) + [replace(fn,name='__liza_owned_'+fn.name) for fn in module if fn.name in owned]
    for fn in functions:
        plan = owned_plans.get(fn.name) or caller_plan(fn, structs, large, owned)
        params = ', '.join((f'ptr %{p["name"]}'
                            if large(p["type"]) else f'{types[p["type"]]} %{p["name"]}') for p in fn.params)
        indirect_result = large(fn.result_type)
        if indirect_result:
            params = f'ptr sret({types[fn.result_type]}) %return_storage' + (', '+params if params else '')
        result_type = 'void' if indirect_result else types[fn.result_type]
        linkage = 'internal ' if fn.name.startswith('file.') else ''
        lines.append(f'define {linkage}{result_type} @liza_{fn.name}({params}) {{')
        refs = {p['name']: f'%{p["name"]}' for p in fn.params}
        value_types = {p['name']: types[p['type']] for p in fn.params}
        logical = {p['name']: p['type'] for p in fn.params}
        logical.update({op.result:op.type for b in fn.blocks for op in b.operations})
        materialized = {'vec.get', 'vec.pop', 'vec.push', 'vec.set', 'view.read', 'array.repeat', 'array.construct', 'struct.construct', 'variant.construct', 'array.update', 'struct.update', 'call', 'phi'}
        # LLVM guards split semantic blocks. Phi edges reference their final labels.
        exits, aliases = {}, {}
        for block in fn.blocks:
            exits[block.name] = block.name
            for op in block.operations:
                refs[op.result] = str(int(op.args[0])) if op.op == 'constant' else f'%{op.result}'
                if large(op.type) and op.op in materialized:
                    refs[op.result] = f'%{op.result}_mem'
                if op.op in ('region.create', 'region.alloc'):
                    if op.op == 'region.alloc': exits[block.name] = f'{op.result}_done'
                if op.op in ('buffer.view','buffer.update'):
                    aliases[op.result] = op.args[0]
                if op.op == 'array.repeat':
                    if large(op.type):
                        exits[block.name] = f'{op.result}_done'
                    elif array_length(op.type) == 0:
                        refs[op.result] = 'zeroinitializer'
                if op.op == 'text.literal':
                    text_size = len(op.args[0].encode('utf-8'))
                    refs[op.result] = f'{{ ptr @text.{fn.name.removeprefix("__liza_owned_")}.{op.result}, i32 {text_size} }}'
                value_types[op.result] = types[op.type]
                if op.op in ('vec.get','vec.pop','vec.push','vec.set'):
                    exits[block.name] = f'{op.result}_done'
                if op.op in ('copy', 'move', 'unpack.consume'):
                    aliases[op.result] = op.args[0]
                if op.op in ('struct.construct', 'array.construct') and not op.args:
                    refs[op.result] = 'zeroinitializer'
                if op.op.startswith('convert.') and op.source_type == 'integer':
                    refs[op.result] = str(convert_integer(int(refs[op.args[0]]), op.type, op.op.split('.')[1]))
                if (op.op == 'convert.checked' and op.source_type != 'integer') or op.overflow == 'trap' or op.shift_policy == 'trap' or op.division_policy == 'trap' or op.bounds_policy == 'trap':
                    exits[block.name] = f'{op.result}_ok'
        aliases.update(plan.aliases)
        for b in fn.blocks:
            for op in b.operations:
                if op.op == 'struct.field' and large(op.type) and structs[op.source_type].fields[0][0] == op.field_name:
                    aliases[op.result] = op.args[0]
        refs['$return'] = '%return_storage'
        # Resolve identities after every SSA reference is known, including
        # forward references across loop backedges and block ordering.
        for name in aliases:
            value = aliases[name]
            while value in aliases:
                value = aliases[value]
            refs[name] = refs[value]
        def canonical(value):
            while value in aliases:
                value = aliases[value]
            return value
        slots = {canonical(op.args[0]) for b in fn.blocks for op in b.operations
                 if op.op in ('array.read', 'view.create') and not large(logical[op.args[0]])}
        calls = [op for b in fn.blocks for op in b.operations if op.op == 'call']
        signatures = {f.name: [p['type'] for p in f.params] for f in functions}
        signatures.update({f.name.text: [t for _,t in f.params] for f in getattr(module,'externals',[])})
        # Large values use immutable storage. Phi edges snapshot in parallel,
        # so reusing a loop's result slot cannot change a previous iteration's value.
        large_phis = {b.name:[op for op in b.operations if op.op == 'phi' and large(op.type)]
                      for b in fn.blocks}
        edges = {}
        for target, phis in large_phis.items():
            if phis:
                for pred in phis[0].incoming_blocks:
                    edges[(pred,target)] = f'{pred}_to_{target}'
        def target_label(pred, target):
            return edges.get((pred,target), target)
        def predecessor_label(pred, target):
            return edges.get((pred,target), exits[pred])
        staged_phis = {op.result for phis in large_phis.values() for op in phis
                       if any(refs[a] != refs[op.result] for a in op.args)}
        pending = []

        def flush():
            for value in pending:
                lines.append(f'  store {value_types[value]} {refs[value]}, ptr %{value}_storage')
            pending.clear()

        for block in fn.blocks:
            lines.append(f'{block.name}:')
            if block is fn.blocks[0]:
                for operation in (op for b in fn.blocks for op in b.operations):
                    if operation.op in ('vec.get','vec.pop','vec.push','vec.set') and not large(operation.type):
                        lines.append(f'  %{operation.result}_scratch = alloca {types[operation.type]}')
                    if operation.op in ('region.create','region.alloc','vec.create','vec.reserve'):
                        lines.append(f'  %{operation.result}_error = alloca i32')
                    if large(operation.type) and operation.op in materialized:
                        if operation.result not in aliases:
                            capacity = size(operation.type)
                            reserves = sorted(plan.reserve.get(operation.result,set()) - {operation.type})
                            for i,t in enumerate(reserves):
                                lines.append(f'  %{operation.result}_larger{i} = icmp ugt i64 {size(t)}, {capacity}')
                                lines.append(f'  %{operation.result}_capacity{i} = select i1 %{operation.result}_larger{i}, i64 {size(t)}, i64 {capacity}')
                                capacity = f'%{operation.result}_capacity{i}'
                            if reserves:
                                lines.append(f'  %{operation.result}_mem = alloca i8, i64 {capacity}, align 16')
                            else:
                                lines.append(f'  %{operation.result}_mem = alloca {types[operation.type]}')
                        if operation.result in staged_phis:
                            lines.append(f'  %{operation.result}_next = alloca {types[operation.type]}')
                    elif operation.op == 'array.update':
                        lines.append(f'  %{operation.result}_scratch = alloca {types[operation.type]}')
                for value in sorted(slots):
                    lines.append(f'  %{value}_storage = alloca {value_types[value]}')
                pending.extend(p['name'] for p in fn.params if p['name'] in slots)

            for op in block.operations:
                if op.op != 'phi':
                    flush()
                name, ty = op.result, types[op.type]
                if op.op in ('constant', 'text.literal', 'copy', 'move', 'unpack.consume') or (op.op.startswith('convert.') and op.source_type == 'integer'):
                    continue
                args = [refs[a] for a in op.args]
                if large(op.type) and op.op == 'phi':
                    continue
                if op.op in ('region.create','region.alloc','vec.create'):
                    if op.op == 'region.create':
                        lines.append(f'  %{name}_ptr = call ptr @liza_rt_region_create(i64 {args[0]}, ptr %{name}_error)')
                        payload_type, payload = 'ptr', f'%{name}_ptr'
                    else:
                        element = types[op.source_type]
                        alignment = f'ptrtoint (ptr getelementptr ({{ i8, {element} }}, ptr null, i32 0, i32 1) to i64)'
                        lines.append(f'  %{name}_ptr = call ptr @liza_rt_region_alloc(ptr {args[0]}, i64 {size(op.source_type)}, i64 {alignment}, i32 {args[1]}, ptr %{name}_error)')
                    lines.extend([f'  %{name}_code = load i32, ptr %{name}_error',
                                  f'  %{name}_failed = icmp ne i32 %{name}_code, 0'])
                    if op.op == 'region.alloc':
                        lines.extend([f'  br i1 %{name}_failed, label %{name}_done, label %{name}_start',
                            f'{name}_start:', f'  br label %{name}_loop', f'{name}_loop:',
                            f'  %{name}_i = phi i32 [0, %{name}_start], [%{name}_next, %{name}_body]',
                            f'  %{name}_end = icmp uge i32 %{name}_i, {args[1]}',
                            f'  br i1 %{name}_end, label %{name}_done, label %{name}_body',
                            f'{name}_body:', f'  %{name}_offset = zext i32 %{name}_i to i64',
                            f'  %{name}_element = getelementptr {element}, ptr %{name}_ptr, i64 %{name}_offset'])
                        write(op.source_type,args[2],f'%{name}_element')
                        lines.extend([f'  %{name}_next = add i32 %{name}_i, 1',f'  br label %{name}_loop',f'{name}_done:',
                            f'  %{name}_buffer0 = insertvalue {{ ptr, i32 }} zeroinitializer, ptr %{name}_ptr, 0',
                            f'  %{name}_buffer = insertvalue {{ ptr, i32 }} %{name}_buffer0, i32 {args[1]}, 1'])
                        payload_type, payload = '{ ptr, i32 }', f'%{name}_buffer'
                    if op.op == 'vec.create':
                        lines.extend([f'  %{name}_vec0 = insertvalue {{ ptr, i32, i32 }} zeroinitializer, ptr %{name}_ptr, 0',
                                      f'  %{name}_vec = insertvalue {{ ptr, i32, i32 }} %{name}_vec0, i32 {args[1]}, 2'])
                        payload_type, payload = '{ ptr, i32, i32 }', f'%{name}_vec'
                    error_type=types['MemoryError']
                    lines.extend([f'  %{name}_tag = zext i1 %{name}_failed to i32',
                        f'  %{name}_error_tag = sub i32 %{name}_code, 1',
                        f'  %{name}_err = insertvalue {error_type} zeroinitializer, i32 %{name}_error_tag, 0',
                        f'  %{name}_result0 = insertvalue {ty} zeroinitializer, i32 %{name}_tag, 0',
                        f'  %{name}_result1 = insertvalue {ty} %{name}_result0, {payload_type} {payload}, 1',
                        f'  %{name} = insertvalue {ty} %{name}_result1, {error_type} %{name}_err, 2'])
                elif op.op.startswith('vec.'):
                    from .vector_backend import emit
                    emit(op,args,refs,types,large,size,write,lines)
                elif op.op == 'unpack.component':
                    if large(op.source_type):
                        ptr = refs[name] if large(op.type) else f'%{name}_ptr'
                        lines.append(f'  {ptr} = getelementptr {types[op.source_type]}, ptr {args[0]}, i32 0, i32 {op.field_name}')
                        if not large(op.type): lines.append(f'  %{name} = load {ty}, ptr {ptr}')
                    else:
                        lines.append(f'  %{name} = extractvalue {types[op.source_type]} {args[0]}, {op.field_name}')
                elif op.op == 'buffer.view':
                    pass # Same physical descriptor, different static rights.
                elif op.op == 'buffer.length':
                    lines.append(f'  %{name} = extractvalue {{ ptr, i32 }} {args[0]}, 1')
                elif op.op == 'buffer.update':
                    lines.extend([f'  %{name}_length = extractvalue {{ ptr, i32 }} {args[0]}, 1',
                        f'  %{name}_invalid = icmp uge i32 {args[1]}, %{name}_length'])
                    guard(name,f'%{name}_invalid')
                    lines.extend([f'  %{name}_base = extractvalue {{ ptr, i32 }} {args[0]}, 0',
                        f'  %{name}_offset = zext i32 {args[1]} to i64',
                        f'  %{name}_ptr = getelementptr {types[op.source_type]}, ptr %{name}_base, i64 %{name}_offset'])
                    write(op.source_type,args[2],f'%{name}_ptr')
                elif op.op in ('buffer.release','region.close'):
                    if op.op == 'region.close': lines.append(f'  call void @liza_rt_region_close(ptr {args[0]})')
                    lines.append(f'  %{name} = add i32 0, 0')
                elif large(op.type) and op.op == 'array.repeat':
                    lines.extend([f'  br label %{name}_start', f'{name}_start:',
                        f'  br label %{name}_loop', f'{name}_loop:',
                        f'  %{name}_i = phi i64 [0, %{name}_start], [%{name}_next, %{name}_body]',
                        f'  %{name}_end = icmp uge i64 %{name}_i, {array_length(op.type)}',
                        f'  br i1 %{name}_end, label %{name}_done, label %{name}_body',
                        f'{name}_body:',
                        f'  %{name}_ptr = getelementptr {ty}, ptr {refs[name]}, i64 0, i64 %{name}_i'])
                    write(element_type(op.type), args[0], f'%{name}_ptr')
                    lines.extend([f'  %{name}_next = add i64 %{name}_i, 1',
                        f'  br label %{name}_loop', f'{name}_done:'])
                elif large(op.type) and op.op in ('struct.construct', 'array.construct', 'variant.construct'):
                    dest = refs[name]
                    if op.op == 'variant.construct':
                        lines.append(f'  call void @llvm.memset.p0.i64(ptr {dest}, i8 0, i64 {size(op.type)}, i1 false)')
                        cases = variants[op.type].cases
                        index = next(i for i,(case,_) in enumerate(cases) if case == op.field_name)
                        lines.append(f'  store i32 {index}, ptr {dest}')
                        fields = [(index+1,cases[index][1],args[0])] if args else []
                    elif op.op == 'array.construct':
                        fields = [(i,element_type(op.type),a) for i,a in enumerate(args)]
                    else:
                        fields = [(i,t,a) for i,((_,t),a) in enumerate(zip(structs[op.type].fields,args))]
                    for i,t,a in fields:
                        ptr = dest if i == 0 else f'%{name}_part{i}'
                        if i != 0:
                            lines.append(f'  {ptr} = getelementptr {ty}, ptr {dest}, i32 0, i32 {i}')
                        write(t,a,ptr)
                elif large(op.type) and op.op in ('array.update','struct.update'):
                    if op.op == 'array.update':
                        lines.append(f'  %{name}_invalid = icmp uge i32 {args[1]}, {array_length(op.type)}')
                        guard(name, f'%{name}_invalid')
                        lines.append(f'  %{name}_offset = zext i32 {args[1]} to i64')
                        index, field_type, value = f'i64 %{name}_offset', element_type(op.type), args[2]
                    else:
                        i = [field for field,_ in structs[op.type].fields].index(op.field_name)
                        index, field_type, value = f'i32 {i}', structs[op.type].fields[i][1], args[1]
                    if name in plan.rebuilt:
                        continue
                    transfer(op.type,args[0],refs[name])
                    lines.append(f'  %{name}_part = getelementptr {ty}, ptr {refs[name]}, i32 0, {index}')
                    write(field_type,value,f'%{name}_part')
                elif op.op in ('struct.field','variant.payload','variant.tag') and large(op.source_type):
                    if op.op == 'struct.field':
                        index = [f for f,_ in structs[op.source_type].fields].index(op.field_name)
                    else:
                        index = 0 if op.op == 'variant.tag' else 1+next(i for i,(case,_) in enumerate(variants[op.source_type].cases) if case == op.field_name)
                    ptr = f'%{name}' if large(op.type) else f'%{name}_ptr'
                    lines.append(f'  {ptr} = getelementptr {types[op.source_type]}, ptr {args[0]}, i32 0, i32 {index}')
                    if not large(op.type): lines.append(f'  %{name} = load {ty}, ptr {ptr}')
                elif op.op == 'sequence.length':
                    if is_array(op.source_type):
                        lines.append(f'  %{name} = add i32 0, {array_length(op.source_type)}')
                    else:
                        lines.append(f'  %{name} = extractvalue {types[op.source_type]} {args[0]}, 1')
                elif op.op == 'variant.construct':
                    cases = variants[op.type].cases
                    index = next(i for i,(case,_) in enumerate(cases) if case==op.field_name)
                    target = name+'_tag' if args else name
                    lines.append(f'  %{target} = insertvalue {ty} zeroinitializer, i32 {index}, 0')
                    if args:
                        lines.append(f'  %{name} = insertvalue {ty} %{target}, {types[cases[index][1]]} {args[0]}, {index+1}')
                elif op.op in ('variant.tag', 'variant.payload'):
                    index = 0 if op.op == 'variant.tag' else 1+next(i for i,(case,_) in enumerate(variants[op.source_type].cases) if case==op.field_name)
                    lines.append(f'  %{name} = extractvalue {types[op.source_type]} {args[0]}, {index}')
                elif op.op in ('array.read', 'view.create', 'view.read'):
                    if op.op == 'view.create':
                        length = array_length(op.source_type)
                        lines.extend([
                            f'  %{name}_order = icmp ugt i32 {args[1]}, {args[2]}',
                            f'  %{name}_end = icmp ugt i32 {args[2]}, {length}',
                            f'  %{name}_invalid = or i1 %{name}_order, %{name}_end',
                        ])
                        guard(name, f'%{name}_invalid')
                        lines.append(f'  %{name}_length = sub i32 {args[2]}, {args[1]}')
                        lines.append(f'  %{name}_offset = zext i32 {args[1]} to i64')
                        storage = args[0] if large(op.source_type) else f'%{canonical(op.args[0])}_storage'
                        lines.append(f'  %{name}_ptr = getelementptr {types[op.source_type]}, ptr {storage}, i64 0, i64 %{name}_offset')
                        lines.append(f'  %{name}_base = insertvalue {ty} zeroinitializer, ptr %{name}_ptr, 0')
                        lines.append(f'  %{name} = insertvalue {ty} %{name}_base, i32 %{name}_length, 1')
                    else:
                        if op.op == 'array.read':
                            length = str(array_length(op.source_type))
                        else:
                            lines.append(f'  %{name}_base = extractvalue {types[op.source_type]} {args[0]}, 0')
                            lines.append(f'  %{name}_length = extractvalue {types[op.source_type]} {args[0]}, 1')
                            length = f'%{name}_length'
                        lines.append(f'  %{name}_invalid = icmp uge i32 {args[1]}, {length}')
                        guard(name, f'%{name}_invalid')
                        lines.append(f'  %{name}_offset = zext i32 {args[1]} to i64')
                        if op.op == 'array.read':
                            storage = args[0] if large(op.source_type) else f'%{canonical(op.args[0])}_storage'
                            lines.append(f'  %{name}_ptr = getelementptr {types[op.source_type]}, ptr {storage}, i64 0, i64 %{name}_offset')
                        else:
                            lines.append(f'  %{name}_ptr = getelementptr {ty}, ptr %{name}_base, i64 %{name}_offset')
                        if large(op.type):
                            if op.op == 'view.read':
                                transfer(op.type, f'%{name}_ptr', refs[name])
                            else:
                                lines.append(f'  %{name} = getelementptr i8, ptr %{name}_ptr, i64 0')
                        else:
                            lines.append(f'  %{name} = load {ty}, ptr %{name}_ptr')
                elif op.op == 'array.update':
                    lines.append(f'  %{name}_invalid = icmp uge i32 {args[1]}, {array_length(op.type)}')
                    guard(name, f'%{name}_invalid')
                    lines.append(f'  store {ty} {args[0]}, ptr %{name}_scratch')
                    lines.append(f'  %{name}_offset = zext i32 {args[1]} to i64')
                    lines.append(f'  %{name}_ptr = getelementptr {ty}, ptr %{name}_scratch, i64 0, i64 %{name}_offset')
                    lines.append(f'  store {types[element_type(op.type)]} {args[2]}, ptr %{name}_ptr')
                    lines.append(f'  %{name} = load {ty}, ptr %{name}_scratch')
                elif op.op == 'struct.update':
                    index = [field for field, _ in structs[op.type].fields].index(op.field_name)
                    field_type = structs[op.type].fields[index][1]
                    lines.append(f'  %{name} = insertvalue {ty} {args[0]}, {types[field_type]} {args[1]}, {index}')
                elif op.op in ('array.construct', 'array.repeat'):
                    if op.op == 'array.repeat':
                        args = args * array_length(op.type)
                    aggregate = 'zeroinitializer'
                    for index, value in enumerate(args):
                        result = name if index == len(args)-1 else f'{name}_element{index}'
                        lines.append(f'  %{result} = insertvalue {ty} {aggregate}, {types[element_type(op.type)]} {value}, {index}')
                        aggregate = f'%{result}'
                elif op.op == 'struct.construct':
                    aggregate = 'zeroinitializer'
                    for index, (value, (_, field_type)) in enumerate(zip(args, structs[op.type].fields)):
                        result = name if index == len(args) - 1 else f'{name}_field{index}'
                        lines.append(f'  %{result} = insertvalue {ty} {aggregate}, {types[field_type]} {value}, {index}')
                        aggregate = f'%{result}'
                elif op.op == 'struct.field':
                    names = [field for field, _ in structs[op.source_type].fields]
                    index = names.index(op.field_name)
                    lines.append(f'  %{name} = extractvalue {types[op.source_type]} {args[0]}, {index}')
                elif op.op.startswith('convert.'):
                    # i128 holds every supported source value and target bound.
                    # Extend by source signedness, then check/clamp mathematically.
                    value = extend(name + '_wide', args[0], op.source_type, 'i128')
                    if op.op == 'convert.checked':
                        range_checks(name, value, 'i128', op.type)
                        lines.append(f'  %{name}_invalid = or i1 %{name}_below, %{name}_above')
                        guard(name, f'%{name}_invalid')
                    elif op.op == 'convert.saturate':
                        value = clamp(name, value, 'i128', op.type)
                    lines.append(f'  %{name} = trunc i128 {value} to {ty}')
                elif op.overflow == 'saturate':
                    # 2N+1 signed bits hold even the product of two unsigned MAXs.
                    wide = f'i{2 * width(op.type) + 1}'
                    left = extend(name + '_left', args[0], op.type, wide)
                    right = extend(name + '_right', args[1], op.type, wide)
                    lines.append(f'  %{name}_wide = {op.op} {wide} {left}, {right}')
                    value = clamp(name, f'%{name}_wide', wide, op.type)
                    lines.append(f'  %{name} = trunc {wide} {value} to {ty}')
                elif op.op == 'call':
                    callee = plan.calls.get(name, op.callee)
                    actuals = []
                    for i,(a,t) in enumerate(zip(op.args,signatures[op.callee])):
                        if large(t):
                            actuals.append(f'ptr {refs[a]}')
                        else:
                            actuals.append(f'{value_types[a]} {refs[a]}')
                    if large(op.type):
                        typed = ', '.join([f'ptr sret({ty}) {refs[name]}'] + actuals)
                        lines.append(f'  call void @liza_{callee}({typed})')
                    else:
                        typed = ', '.join(actuals)
                        lines.append(f'  %{name} = call {ty} @liza_{callee}({typed})')
                elif op.op == 'phi':
                    incoming = ', '.join(f'[ {value}, %{predecessor_label(block_name, block.name)} ]'
                                         for value, block_name in zip(args, op.incoming_blocks))
                    lines.append(f'  %{name} = phi {ty} {incoming}')
                elif op.op in ('not', 'bit_not'):
                    mask = 'true' if op.op == 'not' else '-1'
                    lines.append(f'  %{name} = xor {ty} {args[0]}, {mask}')
                elif op.op in ('eq', 'ne', 'ult', 'ule', 'ugt', 'uge', 'slt', 'sle', 'sgt', 'sge'):
                    lines.append(f'  %{name} = icmp {op.op} {value_types[op.args[0]]} {args[0]}, {args[1]}')
                elif op.op in ('shl', 'shr'):
                    bits = width(op.type)
                    lines.append(f'  %{name}_invalid = icmp uge i32 {args[1]}, {bits}')
                    guard(name, f'%{name}_invalid')
                    count = args[1]
                    if bits != 32:
                        cast = 'trunc' if bits < 32 else 'zext'
                        lines.append(f'  %{name}_count = {cast} i32 {count} to {ty}')
                        count = f'%{name}_count'
                    instruction = 'shl' if op.op == 'shl' else ('ashr' if signed(op.type) else 'lshr')
                    lines.append(f'  %{name} = {instruction} {ty} {args[0]}, {count}')
                elif op.op in ('div', 'rem'):
                    lines.append(f'  %{name}_zero = icmp eq {ty} {args[1]}, 0')
                    invalid = f'%{name}_zero'
                    if signed(op.type) and op.op == 'div':
                        lines.extend([
                            f'  %{name}_min = icmp eq {ty} {args[0]}, {bounds(op.type)[0]}',
                            f'  %{name}_minus_one = icmp eq {ty} {args[1]}, -1',
                            f'  %{name}_overflow = and i1 %{name}_min, %{name}_minus_one',
                            f'  %{name}_invalid = or i1 %{name}_zero, %{name}_overflow',
                        ])
                        invalid = f'%{name}_invalid'
                    guard(name, invalid)
                    divisor = args[1]
                    if signed(op.type) and op.op == 'rem':
                        # x % -1 is always zero. Substitute +1 before srem so
                        # MIN % -1 never executes LLVM's undefined operation.
                        lines.extend([
                            f'  %{name}_minus_one = icmp eq {ty} {divisor}, -1',
                            f'  %{name}_divisor = select i1 %{name}_minus_one, {ty} 1, {ty} {divisor}',
                        ])
                        divisor = f'%{name}_divisor'
                    instruction = ('s' if signed(op.type) else 'u') + op.op
                    lines.append(f'  %{name} = {instruction} {ty} {args[0]}, {divisor}')
                elif op.op in ('and', 'or', 'xor') or op.overflow == 'wrap':
                    lines.append(f'  %{name} = {op.op} {ty} {args[0]}, {args[1]}')
                elif op.overflow == 'trap':
                    sign = 's' if signed(op.type) else 'u'
                    lines.extend([
                        f'  %{name}_pair = call {{{ty}, i1}} @llvm.{sign}{op.op}.with.overflow.{ty}({ty} {args[0]}, {ty} {args[1]})',
                        f'  %{name} = extractvalue {{{ty}, i1}} %{name}_pair, 0',
                        f'  %{name}_overflow = extractvalue {{{ty}, i1}} %{name}_pair, 1',
                    ])
                    guard(name, f'%{name}_overflow')
                else:
                    raise ValueError(f'unsupported IR operation: {op.op}')
                if name in slots:
                    pending.append(name)
            flush()
            term = block.terminator
            if term.op == 'return':
                if indirect_result:
                    transfer(fn.result_type,refs[term.args[0]],'%return_storage')
                    lines.append('  ret void')
                else:
                    lines.append(f'  ret {types[fn.result_type]} {refs[term.args[0]]}')
            elif term.op == 'unreachable':
                lines.append('  unreachable')
            elif term.op == 'switch':
                cases = ' '.join(f'i32 {index}, label %{target_label(block.name, target)}' for index,target in term.args[2:])
                lines.append(f'  switch i32 {refs[term.args[0]]}, label %{target_label(block.name,term.args[1])} [ {cases} ]')
            elif term.op == 'branch':
                condition, then, otherwise = term.args
                lines.append(f'  br i1 {refs[condition]}, label %{target_label(block.name,then)}, label %{target_label(block.name,otherwise)}')
            else:
                lines.append(f'  br label %{target_label(block.name,term.args[0])}')
        for (pred,target), label in edges.items():
            lines.append(label+':')
            phis = [op for op in large_phis[target]
                    if refs[op.args[op.incoming_blocks.index(pred)]] != refs[op.result]]
            for op in phis:
                incoming = op.args[op.incoming_blocks.index(pred)]
                transfer(op.type,refs[incoming],f'%{op.result}_next')
            for op in phis:
                transfer(op.type,f'%{op.result}_next',refs[op.result])
            lines.append(f'  br label %{target}')
        lines.append('}')
    from .cli_backend import entry
    lines.extend(entry(module))
    for intrinsic in ('memmove.p0.p0.i64', 'memset.p0.i64'):
        if not any('call void @llvm.'+intrinsic in line for line in lines):
            lines = [line for line in lines if not line.startswith('declare void @llvm.'+intrinsic)]
    return '\n'.join(lines) + '\n'
