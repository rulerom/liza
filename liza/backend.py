"""Liza IR -> textual LLVM IR. The host toolchain supplies ABI and linking."""


def llvm(module):
    lines = ['; generated by the experimental Liza compiler', 'declare void @llvm.trap()']
    for op in ('add', 'sub', 'mul'):
        lines.append(f'declare {{i32, i1}} @llvm.u{op}.with.overflow.i32(i32, i32)')
    for fn in module:
        params = ', '.join(f'i32 %{p}' for p in fn.params)
        lines.extend([f'define i32 @liza_{fn.name}({params}) {{', 'entry:'])
        refs = {p: f'%{p}' for p in fn.params}
        for op in fn.operations:
            name = op.result
            if op.op == 'constant':
                refs[name] = str(op.args[0])
                continue
            refs[name] = f'%{name}'
            args = [refs[a] for a in op.args]
            if op.op == 'call':
                typed = ', '.join(f'i32 {a}' for a in args)
                lines.append(f'  %{name} = call i32 @liza_{op.callee}({typed})')
            elif op.overflow == 'wrap':
                lines.append(f'  %{name} = {op.op} i32 {args[0]}, {args[1]}')
            else:
                lines.extend([
                    f'  %{name}_pair = call {{i32, i1}} @llvm.u{op.op}.with.overflow.i32(i32 {args[0]}, i32 {args[1]})',
                    f'  %{name} = extractvalue {{i32, i1}} %{name}_pair, 0',
                    f'  %{name}_overflow = extractvalue {{i32, i1}} %{name}_pair, 1',
                    f'  br i1 %{name}_overflow, label %{name}_trap, label %{name}_ok',
                    f'{name}_trap:', '  call void @llvm.trap()', '  unreachable', f'{name}_ok:',
                ])
        lines.extend([f'  ret i32 {refs[fn.returns]}', '}'])
    lines.extend(['define i32 @main() {', 'entry:', '  %result = call i32 @liza_main()',
                  '  ret i32 %result', '}'])
    return '\n'.join(lines) + '\n'
