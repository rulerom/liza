"""Liza IR -> textual LLVM IR. The host toolchain supplies ABI and linking."""
from .types import INTEGER_TYPES, width, signed, bounds, convert_integer


def llvm(module):
    types = {name: f'i{width(name)}' for name in INTEGER_TYPES}
    types['bool'] = 'i1'
    types['integer'] = None  # Only a compile-time conversion literal, never a runtime type.
    lines = ['; generated by the experimental Liza compiler', 'declare void @llvm.trap()']
    intrinsics = sorted({(op.type, op.op) for fn in module for block in fn.blocks
                         for op in block.operations if op.overflow == 'trap'})
    for type_name, op in intrinsics:
        ty, sign = types[type_name], 's' if signed(type_name) else 'u'
        lines.append(f'declare {{{ty}, i1}} @llvm.{sign}{op}.with.overflow.{ty}({ty}, {ty})')

    def guard(name, condition):
        lines.extend([
            f'  br i1 {condition}, label %{name}_trap, label %{name}_ok',
            f'{name}_trap:', '  call void @llvm.trap()', '  unreachable', f'{name}_ok:',
        ])

    def extend(name, value, source, wide):
        instruction = 'sext' if signed(source) else 'zext'
        lines.append(f'  %{name} = {instruction} {types[source]} {value} to {wide}')
        return f'%{name}'

    def range_checks(name, value, wide, target):
        low, high = bounds(target)
        lines.extend([
            f'  %{name}_below = icmp slt {wide} {value}, {low}',
            f'  %{name}_above = icmp sgt {wide} {value}, {high}',
        ])

    def clamp(name, value, wide, target):
        low, high = bounds(target)
        range_checks(name, value, wide, target)
        lines.extend([
            f'  %{name}_lower = select i1 %{name}_below, {wide} {low}, {wide} {value}',
            f'  %{name}_clamped = select i1 %{name}_above, {wide} {high}, {wide} %{name}_lower',
        ])
        return f'%{name}_clamped'

    for fn in module:
        params = ', '.join(f'{types[p["type"]]} %{p["name"]}' for p in fn.params)
        lines.append(f'define {types[fn.result_type]} @liza_{fn.name}({params}) {{')
        refs = {p['name']: f'%{p["name"]}' for p in fn.params}
        value_types = {p['name']: types[p['type']] for p in fn.params}
        # LLVM guards split semantic blocks. Phi edges reference their final labels.
        exits = {}
        for block in fn.blocks:
            exits[block.name] = block.name
            for op in block.operations:
                refs[op.result] = str(int(op.args[0])) if op.op == 'constant' else f'%{op.result}'
                value_types[op.result] = types[op.type]
                if op.op.startswith('convert.') and op.source_type == 'integer':
                    refs[op.result] = str(convert_integer(int(refs[op.args[0]]), op.type, op.op.split('.')[1]))
                if (op.op == 'convert.checked' and op.source_type != 'integer') or op.overflow == 'trap' or op.shift_policy == 'trap' or op.division_policy == 'trap':
                    exits[block.name] = f'{op.result}_ok'
        for block in fn.blocks:
            lines.append(f'{block.name}:')
            for op in block.operations:
                name, ty = op.result, types[op.type]
                if op.op == 'constant' or (op.op.startswith('convert.') and op.source_type == 'integer'):
                    continue
                args = [refs[a] for a in op.args]
                if op.op.startswith('convert.'):
                    # i128 holds every supported source value and target bound.
                    # Extend by source signedness, then check/clamp mathematically.
                    value = extend(name + '_wide', args[0], op.source_type, 'i128')
                    if op.op == 'convert.checked':
                        range_checks(name, value, 'i128', op.type)
                        lines.append(f'  %{name}_invalid = or i1 %{name}_below, %{name}_above')
                        guard(name, f'%{name}_invalid')
                    elif op.op == 'convert.saturate':
                        value = clamp(name, value, 'i128', op.type)
                    lines.append(f'  %{name} = trunc i128 {value} to {ty}')
                elif op.overflow == 'saturate':
                    # 2N+1 signed bits hold even the product of two unsigned MAXs.
                    wide = f'i{2 * width(op.type) + 1}'
                    left = extend(name + '_left', args[0], op.type, wide)
                    right = extend(name + '_right', args[1], op.type, wide)
                    lines.append(f'  %{name}_wide = {op.op} {wide} {left}, {right}')
                    value = clamp(name, f'%{name}_wide', wide, op.type)
                    lines.append(f'  %{name} = trunc {wide} {value} to {ty}')
                elif op.op == 'call':
                    typed = ', '.join(f'{value_types[a]} {refs[a]}' for a in op.args)
                    lines.append(f'  %{name} = call {ty} @liza_{op.callee}({typed})')
                elif op.op == 'phi':
                    incoming = ', '.join(f'[ {value}, %{exits[block_name]} ]'
                                         for value, block_name in zip(args, op.incoming_blocks))
                    lines.append(f'  %{name} = phi {ty} {incoming}')
                elif op.op in ('not', 'bit_not'):
                    mask = 'true' if op.op == 'not' else '-1'
                    lines.append(f'  %{name} = xor {ty} {args[0]}, {mask}')
                elif op.op in ('eq', 'ne', 'ult', 'ule', 'ugt', 'uge', 'slt', 'sle', 'sgt', 'sge'):
                    lines.append(f'  %{name} = icmp {op.op} {value_types[op.args[0]]} {args[0]}, {args[1]}')
                elif op.op in ('shl', 'shr'):
                    bits = width(op.type)
                    lines.append(f'  %{name}_invalid = icmp uge i32 {args[1]}, {bits}')
                    guard(name, f'%{name}_invalid')
                    count = args[1]
                    if bits != 32:
                        cast = 'trunc' if bits < 32 else 'zext'
                        lines.append(f'  %{name}_count = {cast} i32 {count} to {ty}')
                        count = f'%{name}_count'
                    instruction = 'shl' if op.op == 'shl' else ('ashr' if signed(op.type) else 'lshr')
                    lines.append(f'  %{name} = {instruction} {ty} {args[0]}, {count}')
                elif op.op in ('div', 'rem'):
                    lines.append(f'  %{name}_zero = icmp eq {ty} {args[1]}, 0')
                    invalid = f'%{name}_zero'
                    if signed(op.type) and op.op == 'div':
                        lines.extend([
                            f'  %{name}_min = icmp eq {ty} {args[0]}, {bounds(op.type)[0]}',
                            f'  %{name}_minus_one = icmp eq {ty} {args[1]}, -1',
                            f'  %{name}_overflow = and i1 %{name}_min, %{name}_minus_one',
                            f'  %{name}_invalid = or i1 %{name}_zero, %{name}_overflow',
                        ])
                        invalid = f'%{name}_invalid'
                    guard(name, invalid)
                    divisor = args[1]
                    if signed(op.type) and op.op == 'rem':
                        # x % -1 is always zero. Substitute +1 before srem so
                        # MIN % -1 never executes LLVM's undefined operation.
                        lines.extend([
                            f'  %{name}_minus_one = icmp eq {ty} {divisor}, -1',
                            f'  %{name}_divisor = select i1 %{name}_minus_one, {ty} 1, {ty} {divisor}',
                        ])
                        divisor = f'%{name}_divisor'
                    instruction = ('s' if signed(op.type) else 'u') + op.op
                    lines.append(f'  %{name} = {instruction} {ty} {args[0]}, {divisor}')
                elif op.op in ('and', 'or', 'xor') or op.overflow == 'wrap':
                    lines.append(f'  %{name} = {op.op} {ty} {args[0]}, {args[1]}')
                elif op.overflow == 'trap':
                    sign = 's' if signed(op.type) else 'u'
                    lines.extend([
                        f'  %{name}_pair = call {{{ty}, i1}} @llvm.{sign}{op.op}.with.overflow.{ty}({ty} {args[0]}, {ty} {args[1]})',
                        f'  %{name} = extractvalue {{{ty}, i1}} %{name}_pair, 0',
                        f'  %{name}_overflow = extractvalue {{{ty}, i1}} %{name}_pair, 1',
                    ])
                    guard(name, f'%{name}_overflow')
                else:
                    raise ValueError(f'unsupported IR operation: {op.op}')
            term = block.terminator
            if term.op == 'return':
                lines.append(f'  ret {types[fn.result_type]} {refs[term.args[0]]}')
            elif term.op == 'branch':
                condition, then, otherwise = term.args
                lines.append(f'  br i1 {refs[condition]}, label %{then}, label %{otherwise}')
            else:
                lines.append(f'  br label %{term.args[0]}')
        lines.append('}')
    lines.extend(['define i32 @main() {', 'entry:', '  %result = call i32 @liza_main()',
                  '  ret i32 %result', '}'])
    return '\n'.join(lines) + '\n'
